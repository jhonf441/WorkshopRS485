def validate(reg, value):
    """None if the value is valid according to the manual; otherwise, the reason."""
    info = PARAM_TABLE.get(int(reg))
    if info is None:
        return M("t3d_params_not_in_the_manual_table")
    mn, mx, _ = info
    if not mn <= value <= mx:
        return M("t3d_params_out_of_range", min=mn, max=mx)
    for pos, maximum, that in DIGITS.get(int(reg), []):
        d = abs(value) // 10 ** pos % 10
        if d > maximum:
            return M("t3d_params_invalid_digit", digit=d, place=PLACES.get(pos, pos), max=maximum)
    return None
